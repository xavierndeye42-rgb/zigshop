-- ============ Comptes utilisateurs, panier synchronisé, commandes liées au compte ============
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '', phone text not null default '', address text not null default '',
  created_at timestamptz not null default now());
alter table public.profiles enable row level security;
drop policy if exists "Own profile read" on public.profiles;
drop policy if exists "Own profile update" on public.profiles;
create policy "Own profile read" on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy "Own profile update" on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, full_name, phone)
  values (new.id, left(coalesce(new.raw_user_meta_data->>'full_name',''),100), left(coalesce(new.raw_user_meta_data->>'phone',''),20))
  on conflict do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create table if not exists public.carts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb, updated_at timestamptz not null default now());
alter table public.carts enable row level security;
drop policy if exists "Own cart" on public.carts;
create policy "Own cart" on public.carts for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

alter table public.orders add column if not exists user_id uuid references auth.users(id);
drop policy if exists "Own orders read" on public.orders;
create policy "Own orders read" on public.orders for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Own order items read" on public.order_items;
create policy "Own order items read" on public.order_items for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = (select auth.uid())));

