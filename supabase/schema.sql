create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  category text not null check (category in ('homme','femme')),
  price_xof integer not null check (price_xof >= 0),
  image_url text,
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products"
on public.products for select to anon, authenticated
using (active = true);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null,
  customer_phone text not null,
  delivery_address text not null,
  payment_method text not null check (payment_method in ('wave','orange_money')),
  total_xof integer not null check (total_xof >= 0),
  status text not null default 'pending' check (status in ('pending','confirmed','processing','shipped','delivered','cancelled')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','pending','paid','failed')),
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;
-- Aucune politique publique de lecture ou d'écriture des commandes n'est créée ici.
-- La création de commande doit passer par une fonction serveur sécurisée qui valide
-- les prix, le stock et le retour de confirmation du prestataire de paiement.

-- ============ Extensions « version pro » ============
alter table public.products add column if not exists tone text default '#c5d0d9';

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  unit_price_xof integer not null,
  qty integer not null check (qty between 1 and 20)
);
alter table public.order_items enable row level security; -- aucune politique publique

-- Création de commande sécurisée : les prix et le stock sont lus et vérifiés côté base,
-- jamais pris dans le navigateur.
create or replace function public.create_order(p_name text, p_phone text, p_address text, p_method text, p_items jsonb)
returns uuid language plpgsql security definer set search_path = public as $$
declare v_order uuid; v_total integer := 0; it jsonb; pr public.products%rowtype; v_qty integer;
begin
  if length(trim(p_name)) < 2 or length(p_name) > 100 or length(trim(p_phone)) < 8 or length(p_phone) > 20
     or length(trim(p_address)) < 5 or length(p_address) > 250 then raise exception 'Informations invalides'; end if;
  if p_method not in ('wave','orange_money') then raise exception 'Moyen de paiement invalide'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then
    raise exception 'Panier invalide'; end if;
  insert into orders(customer_name, customer_phone, delivery_address, payment_method, total_xof)
  values (trim(p_name), trim(p_phone), trim(p_address), p_method, 0) returning id into v_order;
  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::int;
    select * into pr from products where id = (it->>'product_id')::bigint and active for update;
    if not found or v_qty not between 1 and 20 then raise exception 'Article invalide'; end if;
    if pr.stock < v_qty then raise exception 'stock insuffisant'; end if;
    update products set stock = stock - v_qty where id = pr.id;
    insert into order_items(order_id, product_id, product_name, unit_price_xof, qty) values (v_order, pr.id, pr.name, pr.price_xof, v_qty);
    v_total := v_total + pr.price_xof * v_qty;
  end loop;
  update orders set total_xof = v_total where id = v_order;
  return v_order;
end $$;
revoke all on function public.create_order(text,text,text,text,jsonb) from public;
grant execute on function public.create_order(text,text,text,text,jsonb) to anon, authenticated;

